test('remembers the selected mode after reopening, reloading, and changing planet packs', async ({ page }) => {
  await openPlanner(page)
  await setMode(page, 'Advanced')
  await expect(combo(page, 'DSN level')).toBeVisible()
  await expect(metric(page, 'relay-dsn-range')).toHaveText('1.1 Gm')
  await expect.poll(() => page.evaluate(key => localStorage.getItem(key), storageKey)).toBe('advanced')
  await button(page, 'Close').click()
  await openPlanner(page)
  await expect(modeButton(page, 'Advanced')).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await openPlanner(page)
  await expect(modeButton(page, 'Advanced')).toHaveAttribute('aria-pressed', 'true')
  await button(page, 'Close').click()
  await page.getByRole('button', { name: 'RSS', exact: true }).click()
  await openPlanner(page)
  await expect(modeButton(page, 'Advanced')).toHaveAttribute('aria-pressed', 'true')
  await expect(combo(page, 'Relay body')).toHaveText('Earth')
  await setMode(page, 'Basic')
  await page.reload()
  await openPlanner(page)
  await expect(modeButton(page, 'Basic')).toHaveAttribute('aria-pressed', 'true')
})

