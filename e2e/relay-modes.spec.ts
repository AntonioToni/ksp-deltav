import { readFile } from 'node:fs/promises'
import { expect, test, type Page } from '@playwright/test'

const storageKey = 'ksp-deltav:relay-planner-mode'
const planner = (page: Page) => page.getByRole('dialog', { name: 'CommNet relay planner', exact: true })
const button = (page: Page, name: string) => planner(page).getByRole('button', { name, exact: true })
const field = (page: Page, name: string) => planner(page).getByRole('spinbutton', { name, exact: true })
const combo = (page: Page, name: string) => planner(page).getByRole('combobox', { name, exact: true })
const metric = (page: Page, id: string) => planner(page).getByTestId(id)
const modeGroup = (page: Page) => planner(page).getByRole('group', { name: 'Relay planner mode', exact: true })
const modeButton = (page: Page, mode: 'Basic' | 'Advanced') => modeGroup(page).getByRole('button', { name: mode, exact: true })
const endpoint = (page: Page, side: 'a' | 'b') => planner(page).locator(`[data-signal-endpoint-config="${side}"]`).getByRole('combobox')
let errors: string[]

test.beforeEach(async ({ page }) => {
  errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('./')
})

test.afterEach(() => expect(errors, 'Relay mode changes must not produce browser errors').toEqual([]))

async function openPlanner(page: Page) {
  await page.getByRole('button', { name: 'CommNet relay planner', exact: true }).click()
  await expect(planner(page)).toBeVisible()
}

async function section(page: Page, name: 'Network' | 'Deployment' | 'Body data' | 'Signals') {
  await planner(page).getByRole('tab', { name, exact: true }).click()
}

async function setMode(page: Page, mode: 'Basic' | 'Advanced') {
  await modeButton(page, mode).click()
  await expect(modeButton(page, mode)).toHaveAttribute('aria-pressed', 'true')
}

async function choose(page: Page, label: string, value: string) {
  await combo(page, label).click()
  await page.getByRole('option', { name: value, exact: true }).click()
}

async function chooseEndpoint(page: Page, side: 'a' | 'b', value: string) {
  await endpoint(page, side).click()
  await page.getByRole('option', { name: value, exact: true }).click()
}

async function revealDetails(page: Page, name: RegExp) {
  const details = planner(page).locator('details:visible').filter({ has: page.locator('summary', { hasText: name }) })
  if (await details.getAttribute('open') === null) await details.locator('summary').click()
}

async function importExample(page: Page) {
  const pack = JSON.parse(await readFile('docs/examples/custom-pack.json', 'utf8')) as { name: string }
  await page.getByRole('button', { name: 'Custom planet packs', exact: true }).click()
  const manager = page.getByRole('dialog', { name: 'Planet packs', exact: true })
  await manager.getByRole('tab', { name: 'Custom packs', exact: true }).click()
  await manager.getByLabel('Import planet pack', { exact: true }).setInputFiles({ name: 'basic-mode-body.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(pack)) })
  await manager.getByRole('button', { name: `Use ${pack.name}`, exact: true }).click()
}

